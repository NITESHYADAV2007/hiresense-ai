export function icon(name, { className = "", filled = false } = {}) {
  const ligature =
    LIGATURES[name] ||
    String(name || "")
      .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
      .toLowerCase();
  const fill = filled ? " filled" : "";
  return `<span class="material-symbols-outlined${fill} ${className}" aria-hidden="true">${ligature}</span>`;
}

